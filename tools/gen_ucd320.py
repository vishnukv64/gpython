#!/usr/bin/env python3
"""Generate stdlib/unicodedata/ucd320.go: the Unicode 3.2.0 general-category
and bidirectional-class ranges that stringprep (RFC 3454) needs, taken from
this machine's CPython unicodedata.ucd_3_2_0.

Usage: python3 tools/gen_ucd320.py stdlib/unicodedata/ucd320.go
"""
import sys
import unicodedata

o = unicodedata.ucd_3_2_0


def ranges(f):
    out, prev, st = [], None, 0
    for c in range(0x110000):
        v = f(chr(c))
        if v != prev:
            if prev is not None:
                out.append("%x,%x,%s" % (st, c - 1, prev))
            st, prev = c, v
    out.append("%x,%x,%s" % (st, 0x10FFFF, prev))
    return ";".join(out)


with open(sys.argv[1], "w") as f:
    f.write("// Code generated by tools/gen_ucd320.py; DO NOT EDIT.\n\n")
    f.write("package unicodedata\n\n")
    f.write("const ucd320Cat = %r\n\n" % ranges(o.category))
    f.write("const ucd320Bidi = %r\n" % ranges(o.bidirectional))
